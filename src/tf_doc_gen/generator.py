"""Parse Terraform modules and render their documentation as Markdown."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import hcl2


_RESOURCE_REFERENCE = re.compile(
    r"(?<![\w-])(?:data\.[A-Za-z_][\w-]*\.[A-Za-z_][\w-]*|"
    r"module\.[A-Za-z_][\w-]*|[A-Za-z_][\w-]*\.[A-Za-z_][\w-]*)"
)


class TerraformParseError(ValueError):
    """Raised when a Terraform file cannot be parsed."""


@dataclass
class TerraformModule:
    root: Path
    files: list[Path]
    variables: list[tuple[str, dict[str, Any]]]
    outputs: list[tuple[str, dict[str, Any]]]
    resources: list[tuple[str, str, dict[str, Any]]]
    data_sources: list[tuple[str, str, dict[str, Any]]]
    child_modules: list[tuple[str, dict[str, Any]]]
    terraform_blocks: list[dict[str, Any]]
    examples: list[Path]


def scan_module(root: Path) -> TerraformModule:
    root = root.resolve()
    files = sorted(path for path in root.glob("*.tf") if path.is_file())
    variables: list[tuple[str, dict[str, Any]]] = []
    outputs: list[tuple[str, dict[str, Any]]] = []
    resources: list[tuple[str, str, dict[str, Any]]] = []
    data_sources: list[tuple[str, str, dict[str, Any]]] = []
    child_modules: list[tuple[str, dict[str, Any]]] = []
    terraform_blocks: list[dict[str, Any]] = []

    for path in files:
        try:
            with path.open(encoding="utf-8") as source:
                document = hcl2.load(source)
        except Exception as error:
            raise TerraformParseError(f"{path.relative_to(root)}: {error}") from error

        variables.extend(_named_blocks(document, "variable"))
        outputs.extend(_named_blocks(document, "output"))
        resources.extend(_two_label_blocks(document, "resource"))
        data_sources.extend(_two_label_blocks(document, "data"))
        child_modules.extend(_named_blocks(document, "module"))
        terraform_blocks.extend(_block_bodies(document, "terraform"))

    examples = sorted(
        path
        for path in (root / "examples").rglob("*.tf")
    ) if (root / "examples").is_dir() else []
    return TerraformModule(
        root=root,
        files=files,
        variables=variables,
        outputs=outputs,
        resources=resources,
        data_sources=data_sources,
        child_modules=child_modules,
        terraform_blocks=terraform_blocks,
        examples=examples,
    )


def generate_readme(module: TerraformModule) -> str:
    sections = [
        "# Terraform Module Documentation",
        "",
        "Generated by `tf-doc-gen`. Update the source Terraform files and rerun the generator.",
        "",
        "## Inputs",
        _render_inputs(module.variables),
        "",
        "## Outputs",
        _render_outputs(module.outputs),
        "",
        "## Examples",
        _render_examples(module),
        "",
        "## Architecture Diagram",
        _render_architecture(module),
        "",
        "## Version Compatibility",
        _render_compatibility(module.terraform_blocks),
        "",
        "## Breaking Changes",
        "Breaking changes cannot be inferred reliably from Terraform source. Record versioned migration notes in a `CHANGELOG.md` and review them when upgrading this module.",
    ]
    return "\n".join(sections).rstrip() + "\n"


def _named_blocks(document: dict[str, Any], block_type: str) -> list[tuple[str, dict[str, Any]]]:
    blocks: list[tuple[str, dict[str, Any]]] = []
    for block in document.get(block_type, []):
        for name, body in block.items():
            if name != "__is_block__" and isinstance(body, dict):
                blocks.append((_unquote(name), body))
    return blocks


def _two_label_blocks(document: dict[str, Any], block_type: str) -> list[tuple[str, str, dict[str, Any]]]:
    blocks: list[tuple[str, str, dict[str, Any]]] = []
    for block in document.get(block_type, []):
        labels = [(name, body) for name, body in block.items() if name != "__is_block__"]
        if not labels:
            continue
        first_label, second_level = labels[0]
        if not isinstance(second_level, dict):
            continue
        for second_label, body in second_level.items():
            if second_label != "__is_block__" and isinstance(body, dict):
                blocks.append((_unquote(first_label), _unquote(second_label), body))
    return blocks


def _block_bodies(document: dict[str, Any], block_type: str) -> list[dict[str, Any]]:
    return [body for body in document.get(block_type, []) if isinstance(body, dict)]


def _unquote(value: str) -> str:
    try:
        parsed = json.loads(value)
    except (json.JSONDecodeError, TypeError):
        return value
    return parsed if isinstance(parsed, str) else value


def _plain_value(value: Any) -> str:
    if isinstance(value, str):
        if value.startswith('"') and value.endswith('"'):
            try:
                return str(json.loads(value))
            except json.JSONDecodeError:
                pass
        return value
    if isinstance(value, (dict, list)):
        return json.dumps(value, sort_keys=True)
    return str(value)


def _markdown_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def _render_inputs(variables: list[tuple[str, dict[str, Any]]]) -> str:
    if not variables:
        return "This module does not declare any input variables."
    rows = [
        "| Name | Description | Type | Required | Default |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, body in sorted(variables):
        description = _plain_value(body.get("description", ""))
        value_type = _plain_value(body.get("type", "any"))
        required = "Yes" if "default" not in body else "No"
        default = "-" if required == "Yes" else f"`{_plain_value(body['default'])}`"
        rows.append(
            f"| `{name}` | {_markdown_cell(description) or '-'} | `{value_type}` | {required} | {default} |"
        )
    return "\n".join(rows)


def _render_outputs(outputs: list[tuple[str, dict[str, Any]]]) -> str:
    if not outputs:
        return "This module does not declare any outputs."
    rows = ["| Name | Description | Sensitive |", "| --- | --- | --- |"]
    for name, body in sorted(outputs):
        description = _plain_value(body.get("description", ""))
        sensitive = "Yes" if body.get("sensitive") is True else "No"
        rows.append(f"| `{name}` | {_markdown_cell(description) or '-'} | {sensitive} |")
    return "\n".join(rows)


def _render_examples(module: TerraformModule) -> str:
    lines = [
        "```hcl",
        'module "example" {',
        '  source = "./"',
    ]
    required_variables = [name for name, body in module.variables if "default" not in body]
    if required_variables:
        lines.append("")
        for name in sorted(required_variables):
            lines.append(f"  # TODO: provide a value for required input `{name}`")
    lines.extend(["}", "```"])
    if module.examples:
        lines.extend(["", "Example configurations:"])
        lines.extend(
            f"- [`{path.relative_to(module.root).as_posix()}`]({path.relative_to(module.root).as_posix()})"
            for path in module.examples
        )
    else:
        lines.extend(["", "Add runnable configurations under `examples/` to document complete use cases."])
    return "\n".join(lines)


def _all_strings(value: Any) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, dict):
        return [text for nested in value.values() for text in _all_strings(nested)]
    if isinstance(value, list):
        return [text for nested in value for text in _all_strings(nested)]
    return []


def _render_architecture(module: TerraformModule) -> str:
    nodes: list[tuple[str, dict[str, Any]]] = []
    nodes.extend((f"{kind}.{name}", body) for kind, name, body in module.resources)
    nodes.extend((f"data.{kind}.{name}", body) for kind, name, body in module.data_sources)
    nodes.extend((f"module.{name}", body) for name, body in module.child_modules)
    if not nodes:
        return "No resources, data sources, or child modules found."

    known_addresses = {address for address, _ in nodes}
    edges: set[tuple[str, str]] = set()
    for address, body in nodes:
        for value in _all_strings(body):
            for reference in _RESOURCE_REFERENCE.findall(value):
                if reference in known_addresses and reference != address:
                    edges.add((address, reference))

    identifiers = {address: f"node_{index}" for index, (address, _) in enumerate(sorted(nodes))}
    lines = ["```mermaid", "flowchart LR"]
    for address in sorted(known_addresses):
        label = address.replace('"', "&quot;")
        lines.append(f'  {identifiers[address]}["{label}"]')
    for source, target in sorted(edges):
        lines.append(f"  {identifiers[source]} --> {identifiers[target]}")
    lines.append("```")
    return "\n".join(lines)


def _render_compatibility(terraform_blocks: list[dict[str, Any]]) -> str:
    required_version: str | None = None
    required_providers: dict[str, Any] = {}
    for block in terraform_blocks:
        for key, value in block.items():
            normalized_key = _unquote(key)
            if normalized_key == "required_version":
                required_version = _plain_value(value)
            elif normalized_key == "required_providers":
                provider_blocks = value if isinstance(value, list) else [value]
                for provider_block in provider_blocks:
                    if isinstance(provider_block, dict):
                        required_providers.update(provider_block)

    lines = []
    if required_version:
        lines.append(f"- Terraform: `{required_version}`")
    for name, settings in sorted(required_providers.items()):
        if isinstance(settings, dict):
            source = _plain_value(settings.get("source", ""))
            version = _plain_value(settings.get("version", ""))
            details = ", ".join(
                part for part in (f"source `{source}`" if source else "", f"version `{version}`" if version else "")
                if part
            )
        else:
            details = f"version `{_plain_value(settings)}`"
        lines.append(f"- Provider `{name}`: {details or 'constraint not specified'}")
    if not lines:
        return "No Terraform or provider version constraints were found."
    return "\n".join(lines)
